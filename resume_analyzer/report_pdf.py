"""report_pdf.py - build a clean PDF analysis report (uses reportlab)."""
import io
from xml.sax.saxutils import escape

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import cm
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

TEAL = colors.HexColor("#0F9D8F")
INK = colors.HexColor("#14213D")
GREY = colors.HexColor("#5B6B86")


def _verdict_color(score):
    return TEAL if score >= 70 else colors.HexColor("#D98A0B") if score >= 45 else colors.HexColor("#D64545")


def build_pdf(r):
    """Return the PDF report for an analysis result `r` (from score.analyze) as bytes."""
    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, leftMargin=2 * cm, rightMargin=2 * cm,
                            topMargin=1.8 * cm, bottomMargin=1.8 * cm, title="ResumeLens report")
    base = getSampleStyleSheet()
    h1 = ParagraphStyle("h1", parent=base["Title"], textColor=INK, alignment=0, fontSize=22, spaceAfter=2)
    h2 = ParagraphStyle("h2", parent=base["Heading2"], textColor=INK, fontSize=13, spaceBefore=14, spaceAfter=6)
    body = ParagraphStyle("body", parent=base["BodyText"], fontSize=10, leading=14, textColor=INK)
    small = ParagraphStyle("small", parent=body, fontSize=9, textColor=GREY)

    info = r["info"]
    story = [
        Paragraph("ResumeLens analysis report", h1),
        Paragraph(escape(info["name"] or "Candidate"), small),
        Spacer(1, 10),
    ]

    # headline numbers
    score_color = _verdict_color(r["score"])
    headline = [["Overall score", "Job match", "ATS checks passed", "Skills found"],
                [f"{r['score']}/100", f"{r['match_pct']}%" if r["has_jd"] else "n/a",
                 f"{sum(ok for _, ok, _ in r['ats'])}/{len(r['ats'])}", str(len(info["skills"]))]]
    t = Table(headline, colWidths=[4.2 * cm] * 4)
    t.setStyle(TableStyle([
        ("FONTSIZE", (0, 0), (-1, 0), 9), ("TEXTCOLOR", (0, 0), (-1, 0), GREY),
        ("FONTSIZE", (0, 1), (-1, 1), 18), ("FONTNAME", (0, 1), (-1, 1), "Helvetica-Bold"),
        ("TEXTCOLOR", (0, 1), (0, 1), score_color), ("TEXTCOLOR", (1, 1), (-1, 1), INK),
        ("BOX", (0, 0), (-1, -1), 0.6, colors.HexColor("#D5DCE8")),
        ("INNERGRID", (0, 0), (-1, -1), 0.3, colors.HexColor("#E6EBF3")),
        ("TOPPADDING", (0, 0), (-1, -1), 7), ("BOTTOMPADDING", (0, 0), (-1, -1), 7),
    ]))
    story += [t, Spacer(1, 6)]

    contact = (f"Email: {info['email'] or 'not found'}  |  Phone: {info['phone'] or 'not found'}  |  "
               f"CGPA: {info['cgpa'] or 'not found'}  |  {r['word_count']} words, {r['pages']} page(s)")
    story.append(Paragraph(escape(contact), small))

    # breakdown
    story.append(Paragraph("Score breakdown", h2))
    rows = [["Area", "Marks"]] + [[k, f"{v[0]} / {v[1]}"] for k, v in r["breakdown"].items()]
    bt = Table(rows, colWidths=[8 * cm, 4 * cm])
    bt.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), INK), ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("FONTSIZE", (0, 0), (-1, -1), 9.5),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#F4F7FB")]),
        ("GRID", (0, 0), (-1, -1), 0.3, colors.HexColor("#D5DCE8")),
    ]))
    story.append(bt)

    # skills
    story.append(Paragraph("Skills found", h2))
    story.append(Paragraph(escape(", ".join(sorted(info["skills"])) or "None detected"), body))
    if r["has_jd"]:
        story.append(Paragraph("Job description comparison", h2))
        story.append(Paragraph("<b>Matched:</b> " + escape(", ".join(r["matched"]) or "none"), body))
        story.append(Paragraph("<b>Missing:</b> " + escape(", ".join(r["missing"]) or "none"), body))

    # ATS
    story.append(Paragraph("ATS compatibility", h2))
    for name, ok, tip in r["ats"]:
        mark = "PASS" if ok else "FAIL"
        extra = "" if ok else f" - {escape(tip)}"
        col = "#0F9D8F" if ok else "#D64545"
        story.append(Paragraph(f"<font color='{col}'><b>{mark}</b></font>  {escape(name)}{extra}", body))

    # suggestions
    story.append(Paragraph("What to improve", h2))
    for tip in r["tips"]:
        story.append(Paragraph("&bull; " + escape(tip), body))

    # roles
    story.append(Paragraph("Roles that fit your skills", h2))
    for role, pct, gap in r["roles"]:
        extra = f" (still needed: {escape(', '.join(gap[:5]))})" if gap else ""
        story.append(Paragraph(f"<b>{escape(role)}</b>: {pct}% match{extra}", body))

    story += [Spacer(1, 14), Paragraph(
        "Generated by ResumeLens. Scores are based on keywords and text similarity and are a guide, not a final judgement.", small)]
    doc.build(story)
    return buf.getvalue()
